#!/usr/bin/env python3
"""Writes src/render/overlayBoxes.ts: frame size and opaque box of every
overlay frame, so the game can scale each add-on piece and centre it on the
right point of the astronaut.

Usage: python3 -I tools/overlay_boxes.py public/sprites/items/overlay-*.png
"""
import json
import sys
from pathlib import Path

import numpy as np
from PIL import Image

out = {}
for path in sys.argv[1:]:
    p = Path(path)
    img = np.asarray(Image.open(p).convert('RGBA'))
    h = img.shape[0]
    rows = 2 if p.stem == 'overlay-7' else 4
    frames = 3 * rows
    w = img.shape[1] // frames
    boxes = []
    for i in range(frames):
        a = img[:, i * w:(i + 1) * w, 3]
        ys, xs = np.nonzero(a)
        boxes.append([int(xs.min()), int(ys.min()), int(xs.max()) + 1, int(ys.max()) + 1] if len(xs) else None)
    out[p.stem] = {'w': w, 'h': h, 'boxes': boxes}

Path('src/render/overlayBoxes.ts').write_text(
    '/** Generated by tools/overlay_boxes.py: frame size and opaque box [x0, y0, x1, y1] of each overlay frame. */\n'
    'export const OVERLAY_BOXES: Record<string, { w: number; h: number; boxes: ([number, number, number, number] | null)[] }> = '
    + json.dumps(out) + ';\n'
)
print('boxes for', ', '.join(out))
